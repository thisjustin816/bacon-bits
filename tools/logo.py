"""Draw the Color header: BACON cut like a strip of bacon, then BIT BENCH."""
import math
from pathlib import Path
from PIL import Image
from generated import write_generated
from scenes import encode_tile
ROOT=Path(__file__).resolve().parents[1]
# Header palette 1: sky, cream, red, dark.
SKY,CREAM,RED,DARK=0,1,2,3
WIDTH,HEIGHT=160,24
# Capitals 14 pixels tall with 3-pixel strokes, drawn for the logo only.
GLYPHS={
'B':["#########.","##########","###....###","###....###","###....###","#########.","#########.","###....###","###....###","###....###","###....###","###....###","##########","#########."],
'A':["..######..",".########.","###....###","###....###","###....###","###....###","##########","##########","###....###","###....###","###....###","###....###","###....###","###....###"],
'C':["..#######.",".#########","###.....##","###.......","###.......","###.......","###.......","###.......","###.......","###.......","###.......","###.....##",".#########","..#######."],
'O':["..######..",".########.","###....###","###....###","###....###","###....###","###....###","###....###","###....###","###....###","###....###","###....###",".########.","..######.."],
'N':["###....###","####...###","#####..###","######.###","###.######","###..#####","###...####","###....###","###....###","###....###","###....###","###....###","###....###","###....###"],
'I':["###"]*14,
'T':["#########","#########","...###...","...###...","...###...","...###...","...###...","...###...","...###...","...###...","...###...","...###...","...###...","...###..."],
'E':["#########","#########","###......","###......","###......","########.","########.","###......","###......","###......","###......","###......","#########","#########"],
'H':["###....###"]*5+["##########","##########"]+["###....###"]*7,
}
def ink(text,gap,space):
 """The set of inked pixels for a line of capitals, and its width."""
 pixels=set();x=0
 for ch in text:
  if ch==' ':x+=space;continue
  for y,row in enumerate(GLYPHS[ch]):
   for i,c in enumerate(row):
    if c=='#':pixels.add((x+i,y))
  x+=len(GLYPHS[ch][0])+gap
 return pixels,x-gap
def picture():
 im=Image.new('P',(WIDTH,HEIGHT),SKY)
 bacon,bacon_width=ink('BACON',2,0);rest,rest_width=ink('BIT BENCH',1,6)
 # One pixel of rind on each side of BACON, then a space, then the rest.
 left=(WIDTH-(bacon_width+2+7+rest_width))//2+1;top=(HEIGHT-14)//2
 for x in range(-1,bacon_width+1):
  for y in range(-1,15):
   if (x,y) in bacon:
    # A streak of fat runs the length of the word, rippling like the strip.
    fat=y==6+round(math.sin((x+left)/4.5)*0.8)
    im.putpixel((left+x,top+y),CREAM if fat else RED)
   elif any((x+dx,y+dy) in bacon for dx,dy in ((1,0),(-1,0),(0,1),(0,-1))):im.putpixel((left+x,top+y),DARK)
 for x,y in rest:im.putpixel((left+bacon_width+2+7+x,top+y),DARK)
 return im
def main():
 im=picture();tiles=[];cells=[]
 for ty in range(HEIGHT//8):
  for tx in range(WIDTH//8):
   tile=encode_tile(im,tx,ty)
   if tile not in tiles:tiles.append(tile)
   cells.append(tiles.index(tile))
 output='/* Generated by tools/logo.py: Color header tiles for VRAM bank 1 and their map. */\n'
 output+=f'#define BB_LOGO_TILES {len(tiles)}\n'
 output+='static const uint8_t bb_logo_tiles[]={'+','.join(map(str,b''.join(tiles)))+'};\n'
 output+='static const uint8_t bb_logo_map[]={'+','.join(map(str,cells))+'};\n'
 write_generated(ROOT/'src/logo.h',output)
 print('logo tiles',len(tiles))
if __name__=='__main__':main()
