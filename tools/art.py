"""Generate the original shared font, frames and probe markers."""
from pathlib import Path
from generated import write_generated
from scenes import encode_tile
from PIL import Image,ImageDraw
from lettering import tiles as letter_tiles
ROOT=Path(__file__).resolve().parents[1]
def encode(im):
    return list(b''.join(encode_tile(im,x,y) for y in range(im.height//8) for x in range(im.width//8)))

def array(name,data):
    return 'const unsigned char '+name+'[] = {\n'+''.join('    '+','.join(f'0x{x:02x}' for x in data[i:i+16])+',\n' for i in range(0,len(data),16))+'};\n'

def main():
    (ROOT/'assets').mkdir(exist_ok=True)
    output=array('bb_font',list(letter_tiles()))
    # UI: frame edges, corners, two arrows, filled/empty position markers.
    patterns=[
      ['00000000']*3+['33333333']+['00000000']*4,
      ['00030000']*8,
      ['00000000']*3+['00033333']+['00030000']*4,
      ['00000000']*3+['33330000']+['00030000']*4,
      ['00030000']*3+['00033333']+['00000000']*4,
      ['00030000']*3+['33330000']+['00000000']*4,
      ['00000000','00030000','00330000','03333330','00330000','00030000','00000000','00000000'],
      ['00000000','00003000','00003300','03333330','00003300','00003000','00000000','00000000'],
      ['00000000','00000000','00333000','03333300','00333000','00000000','00000000','00000000'],
      ['00000000','00000000','00333000','03000300','00333000','00000000','00000000','00000000'],
    ]
    patterns.append(['11000000']+['00000000']*7)
    im=Image.new('P',(8*len(patterns),8))
    for i,pat in enumerate(patterns):
      for y,row in enumerate(pat):
       for x,c in enumerate(row):im.putpixel((i*8+x,y),int(c))
    output+=array('bb_chrome',encode(im))
    marks=Image.new('P',(24,8),0);md=ImageDraw.Draw(marks)
    md.rectangle((0,0,7,5),fill=3);md.rectangle((1,1,6,4),fill=1)
    md.rectangle((8,0,15,5),fill=2);md.line((10,1,13,4),fill=3);md.line((13,1,10,4),fill=3)
    md.rectangle((16,0,23,5),fill=2);md.rectangle((19,2,20,3),fill=0)
    output+=array('bb_probes',encode(marks))
    # The header's bottom edge on CGB: sky, then two rows of page color so the
    # title below never touches the sky.
    base=Image.new('P',(8,8),0);ImageDraw.Draw(base).rectangle((0,6,7,7),fill=1)
    output+=array('bb_header_base',encode(base))
    write_generated(ROOT/'src/art.h','/* Generated by tools/art.py from original pixel drawings. */\n'+output)
    write_font_sheet()

def write_font_sheet():
    # A reusable copy of the font: ASCII 32-127 in 16 x 6 cells of 8 x 8,
    # dark ink on white, in the same cell positions the ROM uses.
    font=letter_tiles();sheet=Image.new('P',(128,48),0);sheet.putpalette([255,255,255,40,24,16])
    for i in range(96):
     for y in range(8):
      bits=font[i*16+y*2]
      for x in range(8):
       if bits&(0x80>>x):sheet.putpixel((i%16*8+x,i//16*8+y),1)
    path=ROOT/'assets/font.png'
    if not path.exists() or Image.open(path).convert('1').tobytes()!=sheet.convert('1').tobytes():sheet.save(path)
if __name__=='__main__':main()
