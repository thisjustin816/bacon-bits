"""Original focus borders and sixteen D-pad states, in shared tile format."""
from PIL import ImageDraw
from scenes import ROOT,picture,encode_tile,array
from generated import write_generated

def main():
 output='/* Generated by tools/controls_art.py. */\n'
 slots=list(range(232,240))+list(range(61,65))
 # Right-hand cards and the RTC page share their edge patterns with page one.
 variants=[(0,0),(0,1),(0,2),(0,3),(6,0),(6,1),(5,0),(5,2)]
 for variant,(scene,item) in enumerate(variants):
  x,y=[(4,37),(82,37),(4,85),(82,85)][item]
  im=picture(scene,0)
  # Fill background pixels only. Component pins can reach this shared row.
  for yy in range(y+1,y+43):
   for xx in range(x+1,x+73):
    if (xx<x+4 or xx>=x+68 or yy<y+3) and im.getpixel((xx,yy))==0:im.putpixel((xx,yy),1)
  ImageDraw.Draw(im).rounded_rectangle((x-1,y-1,x+74,y+44),radius=2,outline=3,width=2)
  tiles=[];mapping=[]
  for row in range(7):
   for col in range(10):
    if row not in [0,6] and col not in [0,9]:continue
    tile=encode_tile(im,(10 if item&1 else 0)+col,(10 if item&2 else 4)+row)
    if tile not in tiles:tiles.append(tile)
    mapping.append(slots[tiles.index(tile)])
  assert len(tiles)<=12,(variant,len(tiles))
  tiles.extend([bytes(16)]*(12-len(tiles)))
  output+=array('focus_tiles_'+str(variant),b''.join(tiles))+array('focus_map_'+str(variant),mapping)
 output+='static const uint8_t *const focus_tiles[]={'+','.join('focus_tiles_'+str(i) for i in range(8))+'};\n'
 output+='static const uint8_t *const focus_maps[]={'+','.join('focus_map_'+str(i) for i in range(8))+'};\n'
 write_generated(ROOT/'src/focus_data.h',output)
 tiles=[];maps=[]
 for held in range(16):
  im=picture(4,0);d=ImageDraw.Draw(im)
  for bit,rect,dot in [(4,(42,65,53,77),(47,69,49,71)),(8,(42,96,53,109),(47,101,49,103)),(2,(26,81,38,92),(31,85,33,87)),(1,(57,81,69,92),(62,85,64,87))]:
   if held&bit:d.rectangle(rect,fill=2);d.rectangle(dot,fill=0)
  mapping=[]
  for row in range(6,14):
   for col in range(1,19):
    tile=encode_tile(im,col,row)
    if tile==bytes(16):mapping.append(0);continue
    if tile not in tiles:tiles.append(tile)
    mapping.append(112+tiles.index(tile))
  maps.append(mapping)
 assert len(tiles)==37
 assert max(sum(a!=b for a,b in zip(old,new)) for old in maps for new in maps)<=32, "D-pad update queue too small"
 output='/* Generated by tools/controls_art.py. */\n'+array('button_tiles',b''.join(tiles))
 for i,m in enumerate(maps):output+=array('button_map_'+str(i),m)
 output+='static const uint8_t *const button_maps[]={'+','.join('button_map_'+str(i) for i in range(16))+'};\n'
 write_generated(ROOT/'src/button_data.h',output)
 print('Focus 8 new tiles plus 4 borrowed punctuation slots; live D-pad 37 tiles, no sprites')
if __name__=='__main__':main()
