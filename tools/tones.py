"""Choose stepped frequency divisors covering the complete APU ranges."""
from fractions import Fraction
from pathlib import Path
from generated import write_generated
ROOT=Path(__file__).resolve().parents[1]
targets=[64,65,66,68,70,72,76,80,85,90,96,100,110,120,128,140,160,180,200,220,256,320,440,512,640,880,1024,2048,4096,8192,16384,32768,65536,131072]
registers=[2048-round(131072/x) for x in targets]
# Codes 14 and 15 stop the LFSR. Include every distinct running clock.
clocks={}
for shift in range(14):
 for code,d in enumerate([1,2,4,6,8,10,12,14]):
  f=Fraction(524288,d<<shift)
  clocks.setdefault(f,(shift<<4)|code)
noise=[code for f,code in sorted(clocks.items())]
write_generated(ROOT/'src/tone_table.h','/* Generated by tools/tones.py. */\nconst uint16_t tone_steps[] = {'+','.join(map(str,registers))+'};\nconst uint8_t noise_steps[] = {'+','.join(map(str,noise))+'};\n')
print(f'{len(registers)} pulse/wave steps; {len(noise)} distinct noise clocks')
